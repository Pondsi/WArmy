import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = path.join(root, 'docs/supervisor-state.json');
const state = JSON.parse(fs.readFileSync(file, 'utf8'));
const todo = state.items.filter((x) => x.self && x.status === 'todo');
const doing = state.items.filter((x) => x.self && x.status === 'doing');
const blocked = state.items.filter((x) => x.status === 'blocked');
console.log(`SUPERVISOR round ${state.round}: self todo ${todo.length}, doing ${doing.length}, blocked ${blocked.length}`);
for (const x of [...doing, ...todo]) console.log(`  [${x.status}] #${x.id} ${x.task}`);
for (const x of blocked) console.log(`  [blocked] #${x.id} ${x.task} (needs user)`);
if (!todo.length && !doing.length) console.log('SELF-COMPLETABLE BACKLOG EMPTY');
else console.log('DO NOT STOP: self-completable work remains.');
process.exitCode = todo.length || doing.length ? 3 : 0;
