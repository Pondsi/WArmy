/** 稳定字符串哈希（跨运行可复现）。 */
function hashStr(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

function pick(arr, key) {
  return arr[hashStr(key) % arr.length];
}

