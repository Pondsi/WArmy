function loadSource() {
  const src = fs.readFileSync(SRC, 'utf8');
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(src, ctx, { filename: 'persona-templates.js' });
  const all = ctx.window.__PERSONA_TPL_ALL;
  const byCat = ctx.window.__PERSONA_TPL;
  if (!Array.isArray(all) || !byCat || typeof byCat !== 'object') {
    throw new Error('源文件解析失败：缺少 __PERSONA_TPL_ALL / __PERSONA_TPL');
  }
  return { all, catOrder: Object.keys(byCat) };
}

function itemLines(it, indent, comma) {
  const sp = '  '.repeat(indent);
  return [
    `${sp}{`,
    `${sp}  "id": ${JSON.stringify(it.id)},`,
    `${sp}  "cat": ${JSON.stringify(it.cat)},`,
    `${sp}  "sub": ${JSON.stringify(it.sub)},`,
    `${sp}  "name": ${JSON.stringify(it.name)},`,
    `${sp}  "content": ${JSON.stringify(buildContent(it))}`,
    `${sp}}${comma ? ',' : ''}`,
  ].join('\n');
}

function render(all, catOrder) {
  const itemsByCat = new Map();
  for (const it of all) {
    if (!itemsByCat.has(it.cat)) itemsByCat.set(it.cat, []);
    itemsByCat.get(it.cat).push(it);
  }
  const out = [];
  out.push('/**');
  out.push(' * 「写入认知」预设模版库（分类）。');
  out.push(' * window.__PERSONA_TPL = { 分类: [{id,cat,sub,name,content}] }');
  out.push(' * 下拉选项 = 分类；悬停右侧展开子菜单；顶部可搜名称/内容。');
  out.push(' * 由 scripts/gen-persona-v2.mjs 生成：content 为结构化角色提示词。');
  out.push(' */');
  out.push('window.__PERSONA_TPL = {');
  catOrder.forEach((cat, ci) => {
    const items = itemsByCat.get(cat) || [];
    out.push(`  ${JSON.stringify(cat)}: [`);
    items.forEach((it, ii) => out.push(itemLines(it, 2, ii < items.length - 1)));
    out.push(ci < catOrder.length - 1 ? '  ],' : '  ]');
  });
  out.push('};');
  out.push('window.__PERSONA_TPL_ALL = [');
  all.forEach((it, i) => out.push(itemLines(it, 1, i < all.length - 1)));
  out.push('];');
  out.push('');
  return out.join('\n').replace(/\n/g, '\r\n');
}

function main() {
  const { all, catOrder } = loadSource();
  const text = render(all, catOrder);
  fs.writeFileSync(SRC, text, 'utf8');
  const counts = {};
  let lenSum = 0;
  let min = Infinity;
  let max = 0;
  for (const it of all) {
    counts[it.cat] = (counts[it.cat] || 0) + 1;
    const L = buildContent(it).length;
    lenSum += L;
    if (L < min) min = L;
    if (L > max) max = L;
  }
  console.log('已生成 persona-templates.js');
  for (const c of catOrder) console.log(`  ${c}: ${counts[c]}`);
  console.log(`  TOTAL: ${all.length}`);
  console.log(`  content 平均长度: ${(lenSum / all.length).toFixed(1)} 字（min ${min} / max ${max}）`);
}

main();

