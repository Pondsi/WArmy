function proContent(item) {
  const cat = CATS[item.cat];
  const role = cat.kind === 'office' ? item.sub : cat.roleNoun;
  const task = cat.kind === 'office'
    ? (item.name.includes('·') ? item.name.slice(item.name.indexOf('·') + 1) : item.name)
    : item.sub;
  const key = item.cat + '::' + item.sub;
  const flavor = pick(cat.flavors, key);
  const m1 = pick(cat.methods, key);
  let m2 = pick(cat.methods, item.id);
  if (m2 === m1) m2 = cat.methods[(hashStr(item.id) + 1) % cat.methods.length];
  const p1 = pick(cat.pitfalls, key);
  let p2 = pick(cat.pitfalls, item.id);
  if (p2 === p1) p2 = cat.pitfalls[(hashStr(item.id) + 1) % cat.pitfalls.length];
  return [
    '# 角色定位',
    `${cat.intro(role, task)} ${flavor}`,
    '# 工作方法',
    `- ${m1}`,
    `- ${m2}`,
    '# 输出要求',
    cat.output,
    '# 质量与严谨',
    cat.rigor,
    '# 边界与免责',
    cat.boundary,
    '# 常见误区',
    `- ${p1}`,
    `- ${p2}`,
  ].join('\n');
}

function buildContent(item) {
  if (item.cat === '性格朋友') return friendContent(item.sub, item.name);
  const cat = CATS[item.cat];
  if (!cat) return item.content;
  return proContent(item);
}

