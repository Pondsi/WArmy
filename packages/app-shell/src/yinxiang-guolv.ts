/**
 * 「印象」的隐私过滤器（第 52 轮用户口径）。
 *
 * 用户原话的意思：**印象是一个可以被对外公开的形象**；不能对外公开的个人情况不该留在里面，
 * 应该进**私密知识库**。所以归纳时每条候选都要过一次类目判定：
 *   · 命中敏感类目 ⇒ 不写印象；改写成一条私密知识条目（拿得到私密层写入通道时），写不进去就丢弃并记审计；
 *   · 没命中 ⇒ 照常进印象。
 *
 * 判定口径保守：**认不出就不算敏感**（宁可漏判成"公开"也不能把用户的正常偏好全挡掉），
 * 但类目表要能覆盖真机会伤到人的那几类。每条都用**词组**（不是一个字）匹配，避免"我行/不行"这种误命中。
 */

/** 敏感类目：名称 + 命中词组。名称会写进审计（不改成人看的文案，界面另有 i18n） */
export interface MinGanLei {
  lei: string;
  ci: RegExp;
}

export const MIN_GAN_LEI: MinGanLei[] = [
  { lei: 'jiankang', ci: /(确诊|诊断|病史|复查|化疗|癌症|肿瘤|糖尿病|高血压|心脏病|癫痫|哮喘|抑郁症|焦虑症|双相|精神分裂|自闭症|戒断|服药|用药|心理咨询|精神病|结节|甲状腺|住院|手术|体检|艾滋|HIV|乙肝|慢病|不育)/ },
  { lei: 'xing-bie-xiang', ci: /(性向|同性恋|双性恋|跨性别|变性|出柜|性别认同)/ },
  { lei: 'zongjiao-zhengzhi', ci: /(信佛|信主|信基督|清真|教堂|受洗|皈依|宗教|无神论|政党|政治立场|投票给|上访|维权)/ },
  { lei: 'caiwu-falv', ci: /(负债|贷款|信用卡逾期|破产|银行账号|银行卡号|卡号是|存款|投资亏损|官司|诉讼|被执行|征信|犯罪|案底|前科)/ },
  { lei: 'jiating-xinxi', ci: /(离婚|抚养权|家暴|领养|亲生|婚外|出轨|彩礼)|(妈|爸|爹|娘|儿子|女儿|丈夫|妻子|老公|老婆|哥|姐|弟|妹)(叫|住在|名字是|工作单位)|住在.{0,12}(小区|号院|栋|单元)/ },
  { lei: 'shenfen-zhanghu', ci: /(身份证|护照号|社保号|纳税人识别号|住址是|家庭地址|账号密码|私钥|口令)/ },
  { lei: 'shengyu', ci: /(怀孕|流产|试管婴儿|备孕|绝育|辅助生殖)/ },
];

/**
 * 命中哪一类敏感（返回类名；没命中返回空串）。
 * 只做"词组在句子里"的判定，不做语义推断 —— 语义推断交给整理模型，这里守的是**最后那道硬闸**。
 */
export function minGanLeiMing(wen: string): string {
  const s = String(wen || '');
  if (!s) return '';
  for (const x of MIN_GAN_LEI) { try { if (x.ci.test(s)) return x.lei; } catch { /* 坏正则不算命中 */ } }
  return '';
}

/**
 * 「什么该进认知」的判据（用户口径：认知是**这只牛马**的性格与背景，每只一份，用来让它们不一样）。
 *
 * 一句话：**描述"它是谁、它怎么做事"的进认知；描述"用户是谁、用户要什么"的进印象；
 * "这个会话临时定的规矩"进规范；"全局章法"进术；"用户明令不许/必须"进教条与束缚。**
 */
export function qingShuYinRenZhi(wen: string): boolean {
  const s = String(wen || '').trim();
  if (!s) return false;
  // 主语是牛马自己（习惯、口吻、偏好、专长），且不碰用户隐私类目
  const shiRenZhi = /^我是|^我叫|我(的)?(习惯|一般|通常|不喜欢|喜欢|不爱|擅长|说话|做事|口吻|风格|偏好)/.test(s);
  // "用户的习惯/用户喜欢…" 是印象，不是认知
  const shiYongHu = /^(用户|他|她|老板)|(用户)(的|喜欢|习惯|要|偏好)/.test(s);
  return shiRenZhi && !shiYongHu && minGanLeiMing(s) === '';
}
